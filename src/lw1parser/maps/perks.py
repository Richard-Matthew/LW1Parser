def _normalize_upgrade_name(name: str) -> str:
	"""
	Converts a str to lower and strips punctuation and spaces.
	"""
	name = name.lower()
	name = name.translate(str.maketrans("", "", string.punctuation))
	name = "".join(name.split())
	return name

UPGRADE_MAP_NORMALIZED = {
	_normalize_upgrade_name(name): perk_id
	for perk_id, name in UPGRADE_MAP.items()
}

def UPGRADE_TO_ID(name: str) -> int:
	"""
	Returns the upgrade ID associated with a perk name. Returns
	"""
	key = _normalize_upgrade_name(name)
	return UPGRADE_MAP_NORMALIZED.get(key, 0)

